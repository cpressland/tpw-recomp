"""Generate src/recomp/gen/qmixer_stubs.c: QSound's QMixer (QMixer.dll), unavailable.

QMixer is the game's 3D sound mixer, a DLL on the disc over DirectSound.
Until it is lifted or answered properly the game runs silent: the session
opens (QSWaveMixInitEx returns a handle; with none, the game goes on to use
a sound object it never made, and faults), every other call returns 0, which
is success for those returning an MMRESULT and "no wave" for OpenWaveEx.
Each stub pops what the real export pops (its `ret N`, read from the disc's
QMixer.dll).

    .venv/bin/python -I tools/gen/qmixer_stubs.py game src/recomp/gen/qmixer_stubs.c
"""
import os
import sys

import pefile
from capstone import Cs, CS_ARCH_X86, CS_MODE_32

sys.path.insert(0, os.path.dirname(__file__))
from won_stubs import ret_bytes  # noqa: E402


RETURNS = {'QSWaveMixInitEx': '0x51D0u'}     # a session handle


def main(game, out):
    md = Cs(CS_ARCH_X86, CS_MODE_32)
    exe = pefile.PE(os.path.join(game, 'TP.EXE'))
    used = next([i.name.decode() for i in imp.imports] for imp in exe.DIRECTORY_ENTRY_IMPORT
                if imp.dll.decode().lower() == 'qmixer.dll')
    pe = pefile.PE(os.path.join(game, 'QMixer.dll'))
    exports = {s.name.decode(): s.address for s in pe.DIRECTORY_ENTRY_EXPORT.symbols if s.name}
    rows = []
    for name in sorted(used):
        n = ret_bytes(md, pe, exports[name])
        if n is None:
            sys.exit(f'QMixer!{name}: no ret found')
        rows.append((name, n))
    with open(out, 'w', newline='\n') as f:
        f.write('/* AUTO-GENERATED by tools/gen/qmixer_stubs.py from the disc\'s QMixer.dll.\n'
                ' * QMixer, silent: a session opens, and every call returns 0.\n'
                ' * Each pops what the real export pops (its `ret N`). */\n'
                '#include "win32hle.h"\n\n')
        for name, n in rows:
            value = RETURNS.get(name, '0')
            f.write(f'static void q_{name}(void) {{ RET({value}, {n // 4}); }}\n')
        f.write('\nconst win32hle_shim tpw_qmixer_shims[] = {\n')
        for name, _ in rows:
            f.write(f'    {{ "{name}", q_{name} }},\n')
        f.write('    { 0, 0 }\n};\n')
    print(f'{len(rows)} QMixer calls stubbed -> {out}')


if __name__ == '__main__':
    main(sys.argv[1], sys.argv[2])
