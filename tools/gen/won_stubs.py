"""Generate src/recomp/gen/won_stubs.c: the Won online libraries (wea*.dll), stubbed.

The game links eight of them (auth, chat, city, mail, news, RAS dial-up,
upload, vote), all MSVC C++ classes called __thiscall. The service is long
gone, so each method answers "not connected". What a stub must get right is
how much stack it pops: that is read from the real DLL on the disc, the
`ret N` that ends each export, so nothing here is guessed from the names.

    .venv/bin/python -I tools/gen/won_stubs.py game src/recomp/gen/won_stubs.c
"""
import os
import sys

import pefile
from capstone import Cs, CS_ARCH_X86, CS_MODE_32

DLLS = ['weaauthr', 'weachatr', 'weacityr', 'weamailr', 'weanewsr', 'wearasr', 'weauploadr', 'weavoter']


def ret_bytes(md, pe, rva, hops=4):
    """The stack bytes the export at rva pops: its first ret's immediate,
    following a tail jump (an export that is `jmp body`)."""
    data = pe.get_memory_mapped_image()
    base = pe.OPTIONAL_HEADER.ImageBase
    for ins in md.disasm(data[rva:rva + 0x4000], base + rva):
        if ins.mnemonic == 'ret':
            return int(ins.op_str, 0) if ins.op_str else 0
        if ins.mnemonic == 'jmp':
            if ins.op_str.startswith('0x') and hops:
                return ret_bytes(md, pe, int(ins.op_str, 16) - base, hops - 1)
            return None                     # through a pointer: unknown
    return None


def _name(s, i):
    """Skip a qualified name: fragments until the terminating @. A fragment is
    `name@`, a back-reference digit, or a template `?$name@` + its argument
    types + `@`."""
    while s[i] != '@':
        if s.startswith('?$', i):
            i = s.index('@', i + 2) + 1
            while s[i] != '@':
                i = _type(s, i)[0]
            i += 1
        elif s[i].isdigit():
            i += 1
        else:
            i = s.index('@', i) + 1
    return i + 1


def _type(s, i):
    """Parse one MSVC type at s[i]; return (next index, stack bytes as an argument)."""
    c = s[i]
    if c in 'PQAB':                         # pointer or reference: cv letter, then the pointee
        if s[i + 1] == '6':                 # function pointer: calling convention, ret, params, @Z
            j = i + 3
            j = _type(s, j)[0]
            while not s.startswith('Z', j) and not s.startswith('@Z', j):
                j = _type(s, j)[0]
            return (j + (2 if s.startswith('@Z', j) else 1)), 4
        return _type(s, i + 2)[0], 4
    if c == '_':
        return i + 2, 4                     # _N bool
    if c in 'VUT':                          # class/struct/union by value
        return _name(s, i + 1), 4
    if c == 'N':
        return i + 1, 8                     # double
    if c.isdigit():
        return i + 1, 4                     # back-reference to an earlier argument
    return i + 1, 4                         # C D E F G H I J K M X: 4 bytes on the stack


def mangled_arg_bytes(name):
    """Stack bytes of a __thiscall method's arguments, from its MSVC name."""
    i = _name(name, 1)                      # ?Method@Class@@
    i += 2                                  # access/thiscall letters, e.g. QAE
    if name[i - 2] == 'Q' and name[i - 1] == 'A':
        i += 1                              # Q A E: member, no cv, __thiscall
    i = _type(name, i)[0] if name[i] != '@' else i + 1   # return type
    if name.startswith('XZ', i):
        return 0
    total = 0
    while not name.startswith('@Z', i) and not name.startswith('Z', i):
        i, n = _type(name, i)
        total += n
    return total


def main(game, out):
    md = Cs(CS_ARCH_X86, CS_MODE_32)
    used = {}
    exe = pefile.PE(os.path.join(game, 'TP.EXE'))
    for imp in exe.DIRECTORY_ENTRY_IMPORT:
        dll = imp.dll.decode().lower().rsplit('.', 1)[0]
        if dll in DLLS:
            used[dll] = [i.name.decode() for i in imp.imports]
    rows = []
    for dll in DLLS:
        pe = pefile.PE(os.path.join(game, dll + '.dll'))
        exports = {s.name.decode(): s.address for s in pe.DIRECTORY_ENTRY_EXPORT.symbols if s.name}
        for name in used.get(dll, []):
            # The 2.0 patch updated weachatr and weauploadr; the disc has the
            # 1.x DLLs, so a method new in 2.0 is sized from its name.
            n = ret_bytes(md, pe, exports[name]) if name in exports else mangled_arg_bytes(name)
            if n is None:
                sys.exit(f'{dll}!{name}: no ret found')
            ctor = name.startswith('??0')
            rows.append((dll, name, n, ctor))
    with open(out, 'w', newline='\n') as f:
        f.write('/* AUTO-GENERATED by tools/gen/won_stubs.py from the disc\'s wea*.dll.\n'
                ' * The Won online libraries, stubbed: every method answers "not\n'
                ' * connected" (0), a constructor returns its object. Each pops what\n'
                ' * the real export pops (its `ret N`). */\n'
                '#include "win32hle.h"\n\n')
        for i, (dll, name, n, ctor) in enumerate(rows):
            f.write(f'static void won_{i}(void) {{ RET({"g_ecx" if ctor else "0"}, {n // 4}); }}'
                    f'   /* {dll}: {name} */\n')
        f.write('\nconst win32hle_shim tpw_won_shims[] = {\n')
        for i, (dll, name, n, ctor) in enumerate(rows):
            f.write(f'    {{ "{name}", won_{i} }},\n')
        f.write('    { 0, 0 }\n};\n')
    print(f'{len(rows)} Won methods stubbed -> {out}')


if __name__ == '__main__':
    main(sys.argv[1], sys.argv[2])

